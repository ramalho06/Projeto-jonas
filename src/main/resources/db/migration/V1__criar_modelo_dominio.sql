create table capacidades_diarias (
    id bigint generated by default as identity,
    dia date not null unique,
    horas_disponiveis numeric(8,2) not null,
    horas_reservadas numeric(8,2) not null,
    revisao bigint not null,
    primary key (id),
    check (horas_disponiveis >= 0),
    check (horas_reservadas between 0 and horas_disponiveis)
);

create table materiais (
    id bigint generated by default as identity,
    quantidade_fisica numeric(15,3) not null,
    quantidade_reservada numeric(15,3) not null,
    revisao bigint not null,
    nome varchar(255) not null,
    unidade_medida varchar(255) not null,
    primary key (id),
    check (quantidade_fisica >= 0),
    check (quantidade_reservada between 0 and quantidade_fisica)
);

create table usuarios (
    id bigint generated by default as identity,
    ativo boolean not null,
    email varchar(255) not null unique,
    nome varchar(255) not null,
    perfil varchar(255) not null check ((perfil in ('ADMINISTRADOR','FUNCIONARIO','CLIENTE'))),
    senha_codificada varchar(255) not null,
    primary key (id)
);

create table clientes (
    id bigint generated by default as identity,
    usuario_id bigint unique,
    contato varchar(255) not null,
    nome varchar(255) not null,
    primary key (id),
    foreign key (usuario_id) references usuarios (id)
);

create table encomendas (
    id bigint generated by default as identity,
    data_solicitada date not null,
    numero_versao_vigente integer not null,
    cadastrada_em timestamp(6) with time zone not null,
    cliente_id bigint not null,
    materiais_conferidos_em timestamp(6) with time zone,
    materiais_conferidos_por_id bigint,
    responsavel_id bigint not null,
    revisao bigint not null,
    canal_origem varchar(255) not null check ((canal_origem in ('WHATSAPP','INSTAGRAM','PRESENCIAL','TELEFONE','PORTAL'))),
    codigo varchar(255) not null unique,
    motivo_cancelamento text,
    motivo_reprovacao text,
    status varchar(255) not null check ((status in ('PENDENTE','APROVADA','REPROVADA','EM_PRODUCAO','PRONTA','ENTREGUE','CANCELADA'))),
    primary key (id),
    foreign key (cliente_id) references clientes (id),
    foreign key (materiais_conferidos_por_id) references usuarios (id),
    foreign key (responsavel_id) references usuarios (id)
);

create table custos_encomenda (
    id bigint generated by default as identity,
    valor numeric(15,2) not null,
    encomenda_id bigint not null,
    registrado_em timestamp(6) with time zone not null,
    responsavel_id bigint not null,
    categoria varchar(255) not null check ((categoria in ('MATERIAL','MAO_DE_OBRA','ENTREGA','RETRABALHO','PERDA'))),
    descricao text not null,
    primary key (id),
    foreign key (encomenda_id) references encomendas (id),
    foreign key (responsavel_id) references usuarios (id),
    check (valor >= 0)
);

create table entregas (
    id bigint generated by default as identity,
    encomenda_id bigint not null unique,
    registrada_em timestamp(6) with time zone not null,
    registrada_por_id bigint not null,
    modalidade varchar(255) not null check ((modalidade in ('ENTREGA','RETIRADA'))),
    primary key (id),
    foreign key (encomenda_id) references encomendas (id),
    foreign key (registrada_por_id) references usuarios (id)
);

create table funcoes_usuario (
    usuario_id bigint not null,
    funcao varchar(255) not null check ((funcao in ('ATENDIMENTO','PRODUCAO','FINANCEIRO','ENTREGA'))),
    primary key (usuario_id, funcao),
    foreign key (usuario_id) references usuarios (id)
);

create table historicos_encomenda (
    id bigint generated by default as identity,
    visivel_ao_cliente boolean not null,
    autor_id bigint,
    encomenda_id bigint not null,
    ocorrida_em timestamp(6) with time zone not null,
    dados_anteriores text,
    dados_novos text,
    justificativa text,
    operacao varchar(255) not null check ((operacao in ('CADASTRADA','STATUS_ALTERADO','ALTERACAO_SOLICITADA','ALTERACAO_APROVADA','ALTERACAO_REJEITADA','ALTERACAO_EXPIRADA','IMPEDIMENTO_REGISTRADO','IMPEDIMENTO_RESOLVIDO','CIENCIA_REGISTRADA','PAGAMENTO_REGISTRADO','PAGAMENTO_ESTORNADO','CANCELADA','ENTREGUE'))),
    primary key (id),
    foreign key (autor_id) references usuarios (id),
    foreign key (encomenda_id) references encomendas (id)
);

create table impedimentos_producao (
    id bigint generated by default as identity,
    encomenda_id bigint not null,
    registrado_em timestamp(6) with time zone not null,
    resolvido_em timestamp(6) with time zone,
    responsavel_id bigint not null,
    descricao text not null,
    primary key (id),
    foreign key (encomenda_id) references encomendas (id),
    foreign key (responsavel_id) references usuarios (id)
);

create table itens_encomenda (
    id bigint generated by default as identity,
    quantidade integer not null,
    encomenda_id bigint not null,
    personalizacao text not null,
    tipo_produto varchar(255) not null,
    primary key (id),
    foreign key (encomenda_id) references encomendas (id),
    check (quantidade > 0)
);

create table materiais_item_encomenda (
    quantidade numeric(15,3) not null,
    item_id bigint not null,
    material_id bigint not null,
    foreign key (material_id) references materiais (id),
    foreign key (item_id) references itens_encomenda (id),
    check (quantidade > 0)
);

create table notificacoes (
    id bigint generated by default as identity,
    criada_em timestamp(6) with time zone not null,
    destinatario_id bigint not null,
    evento_id bigint not null,
    lida_em timestamp(6) with time zone,
    primary key (id),
    unique (destinatario_id, evento_id),
    foreign key (destinatario_id) references usuarios (id),
    foreign key (evento_id) references historicos_encomenda (id)
);

create table pagamentos (
    id bigint generated by default as identity,
    valor numeric(15,2) not null,
    encomenda_id bigint not null,
    recebido_em timestamp(6) with time zone not null,
    responsavel_id bigint not null,
    chave_operacao varchar(255) not null,
    forma varchar(255) not null check ((forma in ('PIX','DINHEIRO','CARTAO','TRANSFERENCIA','OUTRA'))),
    primary key (id),
    unique (encomenda_id, chave_operacao),
    foreign key (encomenda_id) references encomendas (id),
    foreign key (responsavel_id) references usuarios (id),
    check (valor > 0)
);

create table estornos_pagamento (
    id bigint generated by default as identity,
    autor_id bigint not null,
    pagamento_id bigint not null unique,
    registrado_em timestamp(6) with time zone not null,
    justificativa text not null,
    primary key (id),
    foreign key (autor_id) references usuarios (id),
    foreign key (pagamento_id) references pagamentos (id)
);

create table reservas_capacidade (
    id bigint generated by default as identity,
    horas numeric(8,2) not null,
    capacidade_id bigint not null,
    criada_em timestamp(6) with time zone not null,
    encomenda_id bigint not null,
    liberada_em timestamp(6) with time zone,
    primary key (id),
    foreign key (capacidade_id) references capacidades_diarias (id),
    foreign key (encomenda_id) references encomendas (id),
    check (horas > 0)
);

create table reservas_material (
    id bigint generated by default as identity,
    quantidade numeric(15,3) not null,
    saldo_reservado numeric(15,3) not null,
    autor_id bigint not null,
    criada_em timestamp(6) with time zone not null,
    encomenda_id bigint not null,
    material_id bigint not null,
    primary key (id),
    foreign key (autor_id) references usuarios (id),
    foreign key (encomenda_id) references encomendas (id),
    foreign key (material_id) references materiais (id),
    check (quantidade > 0),
    check (saldo_reservado between 0 and quantidade)
);

create table movimentacoes_estoque (
    id bigint generated by default as identity,
    quantidade numeric(15,3) not null,
    autor_id bigint not null,
    material_id bigint not null,
    ocorrida_em timestamp(6) with time zone not null,
    reserva_id bigint,
    motivo text,
    tipo varchar(255) not null check ((tipo in ('ENTRADA','SAIDA','CONSUMO','PERDA'))),
    primary key (id),
    foreign key (autor_id) references usuarios (id),
    foreign key (material_id) references materiais (id),
    foreign key (reserva_id) references reservas_material (id),
    check (quantidade > 0)
);

create table versoes_encomenda (
    id bigint generated by default as identity,
    desconto numeric(15,2) not null,
    esforco_horas numeric(8,2) not null,
    numero integer not null,
    prazo_prometido date not null,
    preco_bruto numeric(15,2) not null,
    aprovada_em timestamp(6) with time zone not null,
    aprovada_por_id bigint not null,
    encomenda_id bigint not null,
    inicio_planejado_em timestamp(6) with time zone not null,
    limite_alteracao timestamp(6) with time zone not null,
    primary key (id),
    unique (encomenda_id, numero),
    foreign key (aprovada_por_id) references usuarios (id),
    foreign key (encomenda_id) references encomendas (id)
);

create table ciencias_producao (
    id bigint generated by default as identity,
    confirmada_em timestamp(6) with time zone not null,
    funcionario_id bigint not null,
    versao_id bigint not null,
    primary key (id),
    foreign key (funcionario_id) references usuarios (id),
    foreign key (versao_id) references versoes_encomenda (id)
);

create table itens_versao_encomenda (
    id bigint generated by default as identity,
    ordem integer not null,
    quantidade integer not null,
    versao_id bigint not null,
    personalizacao text not null,
    tipo_produto varchar(255) not null,
    primary key (id),
    foreign key (versao_id) references versoes_encomenda (id),
    check (ordem >= 0),
    check (quantidade > 0)
);

create table materiais_item_versao (
    quantidade numeric(15,3) not null,
    item_id bigint not null,
    material_id bigint not null,
    foreign key (material_id) references materiais (id),
    foreign key (item_id) references itens_versao_encomenda (id),
    check (quantidade > 0)
);

create table parcelas_previstas (
    id bigint generated by default as identity,
    valor numeric(15,2) not null,
    vencimento date not null,
    versao_id bigint not null,
    primary key (id),
    foreign key (versao_id) references versoes_encomenda (id),
    check (valor > 0)
);

create table solicitacoes_alteracao (
    id bigint generated by default as identity,
    desconto numeric(15,2) not null,
    esforco_horas numeric(8,2) not null,
    prazo_prometido date not null,
    preco_bruto numeric(15,2) not null,
    analisada_em timestamp(6) with time zone,
    analisada_por_id bigint,
    concordancia_em timestamp(6) with time zone,
    encomenda_id bigint not null,
    inicio_planejado_em timestamp(6) with time zone not null,
    limite_alteracao timestamp(6) with time zone not null,
    registrada_por_id bigint not null,
    solicitada_em timestamp(6) with time zone not null,
    versao_base_id bigint not null,
    canal varchar(255) not null check ((canal in ('WHATSAPP','INSTAGRAM','PRESENCIAL','TELEFONE','PORTAL'))),
    justificativa text,
    status varchar(255) not null check ((status in ('PENDENTE','AGUARDANDO_CONCORDANCIA','AUTORIZADA','APLICADA','REJEITADA','EXPIRADA'))),
    primary key (id),
    foreign key (analisada_por_id) references usuarios (id),
    foreign key (encomenda_id) references encomendas (id),
    foreign key (registrada_por_id) references usuarios (id),
    foreign key (versao_base_id) references versoes_encomenda (id)
);

create table itens_propostos (
    id bigint generated by default as identity,
    ordem integer not null,
    quantidade integer not null,
    solicitacao_id bigint not null,
    personalizacao text not null,
    tipo_produto varchar(255) not null,
    primary key (id),
    foreign key (solicitacao_id) references solicitacoes_alteracao (id),
    check (ordem >= 0),
    check (quantidade > 0)
);

create table materiais_item_proposto (
    quantidade numeric(15,3) not null,
    item_id bigint not null,
    material_id bigint not null,
    foreign key (material_id) references materiais (id),
    foreign key (item_id) references itens_propostos (id),
    check (quantidade > 0)
);
